func TestBuilderAutoTime(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		mustExec(t, db, "DROP TABLE IF EXISTS stamps")
		if db.Dialect().Name() == "mysql" {
			mustExec(t, db, `CREATE TABLE stamps (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(20) NOT NULL,
				created_at DATETIME(6) NOT NULL, updated_at DATETIME(6) NOT NULL)`)
		} else {
			mustExec(t, db, `CREATE TABLE stamps (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(20) NOT NULL,
				created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL)`)
		}

		before := time.Now().Add(-time.Second)
		s := Stamp{Name: "a"}
		if _, err := xdb.Insert(db, &s).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if s.CreatedAt.Before(before) || s.UpdatedAt.Before(before) {
			t.Fatalf("timestamps not filled: %+v", s)
		}

		// 值确实落库
		got, err := xdb.Query[Stamp](db).Where(xdb.CNum[int64](xdb.T("stamps"), "id").Eq(s.ID)).One(ctx)
		if err != nil || !got.CreatedAt.Equal(s.CreatedAt) || !got.UpdatedAt.Equal(s.UpdatedAt) {
			t.Fatalf("roundtrip: %+v vs %+v (%v)", got, s, err)
		}

		// UPDATE 只改 updated_at，不动 created_at
		origCreated, origUpdated := s.CreatedAt, s.UpdatedAt
		time.Sleep(5 * time.Millisecond)
		s.Name = "b"
		if _, err := xdb.UpdateModel(db, &s).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		if !s.CreatedAt.Equal(origCreated) {
			t.Fatalf("created_at must not change on update: %v -> %v", origCreated, s.CreatedAt)
		}
		if !s.UpdatedAt.After(origUpdated) {
			t.Fatalf("updated_at must advance: %v -> %v", origUpdated, s.UpdatedAt)
		}
		again, err := xdb.Query[Stamp](db).Where(xdb.CNum[int64](xdb.T("stamps"), "id").Eq(s.ID)).One(ctx)
		if err != nil || again.Name != "b" || !again.UpdatedAt.Equal(s.UpdatedAt) {
			t.Fatalf("after update: %+v %v", again, err)
		}
	})
}

func TestBuilderPreload(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		seed(t, db)

		// has_many：一次额外查询加载全部订单
		cs, err := xdb.Query[Customer](db).OrderBy(U.ID.Asc()).Preload("Orders").All(ctx)
		if err != nil || len(cs) != 3 {
			t.Fatalf("%v %v", cs, err)
		}
		if len(cs[0].Orders) != 3 || len(cs[1].Orders) != 0 || len(cs[2].Orders) != 1 {
			t.Fatalf("orders per customer: %d %d %d", len(cs[0].Orders), len(cs[1].Orders), len(cs[2].Orders))
		}
		// 未 preload 的关联保持零值（不做隐式懒加载）
		plain, err := xdb.Query[Customer](db).Where(U.ID.Eq(cs[0].ID)).One(ctx)
		if err != nil || plain.Orders != nil {
			t.Fatalf("lazy loading must not happen: %+v %v", plain.Orders, err)
		}

		// 带条件的 preload
		filtered, err := xdb.Query[Customer](db).Where(U.ID.Eq(cs[0].ID)).
			Preload("Orders", O.State.Eq("paid")).One(ctx)
		if err != nil || len(filtered.Orders) != 2 {
			t.Fatalf("filtered preload: %d %v", len(filtered.Orders), err)
		}

		// belongs_to：从订单反查客户
		os, err := xdb.Query[Order](db).OrderBy(O.ID.Asc()).Preload("Customer").All(ctx)
		if err != nil || len(os) != 4 {
			t.Fatalf("%v %v", os, err)
		}
		if os[0].Customer == nil || os[0].Customer.Name != "alice" {
			t.Fatalf("belongs_to: %+v", os[0].Customer)
		}

		// 未知关联报错而不是静默忽略
		if _, err := xdb.Query[Customer](db).Preload("Nope").All(ctx); !errors.Is(err, xdb.ErrUnknownRelation) {
			t.Fatalf("want ErrUnknownRelation, got %v", err)
		}
	})
}

