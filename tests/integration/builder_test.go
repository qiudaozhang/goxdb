type Customer struct {
	ID        int64     `xdb:"id,pk,auto"`
	Name      string    `xdb:"name"`
	Email     *string   `xdb:"email"`
	Age       int       `xdb:"age"`
	CreatedAt time.Time `xdb:"created_at"`
}

// Stamp 验证 autoCreateTime / autoUpdateTime 在真实库里写入正确的值。
type Stamp struct {
	ID        int64     `xdb:"id,pk,auto"`
	Name      string    `xdb:"name"`
	CreatedAt time.Time `xdb:"created_at,autoCreateTime"`
	UpdatedAt time.Time `xdb:"updated_at,autoUpdateTime"`
}

type Order struct {
	ID         int64  `xdb:"id,pk,auto"`
	CustomerID int64  `xdb:"customer_id"`
	Amount     int64  `xdb:"amount"`
	State      string `xdb:"state"`
}

type customerTable struct {
	xdb.Table
	ID        xdb.NumberCol[int64]
	Name      xdb.StringCol
	Email     xdb.StringCol
	Age       xdb.NumberCol[int]
	CreatedAt xdb.TimeCol
}

func newCustomerTable(t xdb.Table) customerTable {
	return customerTable{t, xdb.CNum[int64](t, "id"), xdb.CStr(t, "name"), xdb.CStr(t, "email"), xdb.CNum[int](t, "age"), xdb.CTime(t, "created_at")}
}

type orderTable struct {
	xdb.Table
	ID         xdb.NumberCol[int64]
	CustomerID xdb.NumberCol[int64]
	Amount     xdb.NumberCol[int64]
	State      xdb.StringCol
}

func newOrderTable(t xdb.Table) orderTable {
	return orderTable{t, xdb.CNum[int64](t, "id"), xdb.CNum[int64](t, "customer_id"), xdb.CNum[int64](t, "amount"), xdb.CStr(t, "state")}
}

func (o orderTable) As(a string) orderTable { return newOrderTable(o.Table.As(a)) }

var (
	U = newCustomerTable(xdb.TableOf[Customer]())
	O = newOrderTable(xdb.TableOf[Order]())
)

func setupShop(t *testing.T, db *xdb.DB) {
	t.Helper()
	mustExec(t, db, "DROP TABLE IF EXISTS orders")
	mustExec(t, db, "DROP TABLE IF EXISTS customers")
	mustExec(t, db, "DROP TABLE IF EXISTS nodes")
	if db.Dialect().Name() == "mysql" {
		mustExec(t, db, `CREATE TABLE customers (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(50) NOT NULL UNIQUE,
			email VARCHAR(100), age INT NOT NULL DEFAULT 0, created_at DATETIME(6) NOT NULL)`)
		mustExec(t, db, `CREATE TABLE orders (id BIGINT AUTO_INCREMENT PRIMARY KEY, customer_id BIGINT NOT NULL,
			amount BIGINT NOT NULL, state VARCHAR(20) NOT NULL)`)
	} else {
		mustExec(t, db, `CREATE TABLE customers (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(50) NOT NULL UNIQUE,
			email VARCHAR(100), age INT NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL)`)
		mustExec(t, db, `CREATE TABLE orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT NOT NULL,
			amount BIGINT NOT NULL, state VARCHAR(20) NOT NULL)`)
	}
	mustExec(t, db, "CREATE TABLE nodes (id BIGINT PRIMARY KEY, parent_id BIGINT)")
}

var t0 = time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC)

func seed(t *testing.T, db *xdb.DB) []Customer {
	t.Helper()
	cs := []Customer{
		{Name: "alice", Age: 30, CreatedAt: t0},
		{Name: "bob", Age: 17, CreatedAt: t0},
		{Name: "carol_50%", Age: 65, CreatedAt: t0, Email: strp("C@X.COM")},
	}
	if n, err := xdb.InsertMany(db, cs).Exec(ctx); err != nil || n != 3 {
		t.Fatalf("insert customers: %d %v", n, err)
	}
	var orders []Order
	for _, o := range []struct {
		c      int
		amount int64
		state  string
	}{{0, 100, "paid"}, {0, 50, "paid"}, {0, 10, "new"}, {2, 300, "paid"}} {
		orders = append(orders, Order{CustomerID: cs[o.c].ID, Amount: o.amount, State: o.state})
	}
	if _, err := xdb.InsertMany(db, orders).Batch(3).Exec(ctx); err != nil {
		t.Fatal(err)
	}
	return cs
}

func strp(s string) *string { return &s }

func TestBuilderInsertBackfill(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		cs := seed(t, db)
		for _, c := range cs {
			got, err := xdb.Query[Customer](db).Where(U.ID.Eq(c.ID)).One(ctx)
			if err != nil || got.Name != c.Name || !got.CreatedAt.Equal(t0) {
				t.Fatalf("backfilled id %d does not match row: %+v %v", c.ID, got, err)
			}
		}
		one := Customer{Name: "dave", CreatedAt: t0}
		if _, err := xdb.Insert(db, &one).Exec(ctx); err != nil || one.ID == 0 {
			t.Fatal(one.ID, err)
		}
	})
}

type CustomerStat struct {
	CustomerID int64  `xdb:"customer_id"`
	Name       string `xdb:"name"`
	Total      int64  `xdb:"total"`
	Cnt        int64  `xdb:"cnt"`
}

func TestBuilderQueries(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		cs := seed(t, db)

		adults, err := xdb.Query[Customer](db).Where(U.Age.Ge(18)).OrderBy(U.ID.Asc()).All(ctx)
		if err != nil || len(adults) != 2 || adults[1].Name != "carol_50%" {
			t.Fatal(adults, err)
		}
		// Contains 按字面匹配 % 与 _
		lit, err := xdb.Query[Customer](db).Where(U.Name.Contains("_50%")).Count(ctx)
		if err != nil || lit != 1 {
			t.Fatal(lit, err)
		}
		if n, err := xdb.Query[Customer](db).Where(U.Email.ILike("c@x%")).Count(ctx); err != nil || n != 1 {
			t.Fatal("ilike", n, err)
		}

		o := O.As("o")
		// SUM(BIGINT) 在 MySQL 返回 DECIMAL、在 PG 返回 NUMERIC，两边都扫不进 int64。
		// 显式 CAST 成 BIGINT，使同一个 DTO 在两个方言下都成立。
		total := xdb.Cast[int64]("BIGINT", xdb.Sum(o.Amount))
		stats, err := xdb.Select[CustomerStat](db,
			U.ID.As("customer_id"), U.Name,
			xdb.Coalesce(total, 0).As("total"),
			xdb.CountOf(o.ID).As("cnt"),
		).From(U).
			LeftJoin(o, o.CustomerID.EqCol(U.ID), o.State.Eq("paid")).
			GroupBy(U.ID, U.Name).
			Having(xdb.Coalesce(total, 0).Ge(100)).
			OrderBy(xdb.C[int64](nil, "total").Desc()).
			All(ctx)
		if err != nil || len(stats) != 2 || stats[0].Total != 300 || stats[1].Total != 150 || stats[1].Cnt != 2 {
			t.Fatalf("%+v %v", stats, err)
		}

		// IN 子查询 + EXISTS + 标量子查询
		paid := xdb.Select[int64](nil, O.CustomerID).From(O).Where(O.State.Eq("paid"))
		withPaid, err := xdb.Pluck(ctx, xdb.Query[Customer](db).Where(U.ID.InSub(paid)).OrderBy(U.ID.Asc()), U.ID)
		if err != nil || len(withPaid) != 2 {
			t.Fatal(withPaid, err)
		}
		// EXISTS 的投影只需占位；用字面量而不是绑定参数，
		// 因为 PostgreSQL 无法推断裸 $1 的类型（报 for text (OID 25)）。
		noOrders, err := xdb.Query[Customer](db).Where(xdb.NotExists(
			xdb.Select[int](nil, xdb.SQL[int]("1")).From(O).Where(O.CustomerID.EqCol(U.ID)))).One(ctx)
		if err != nil || noOrders.Name != "bob" {
			t.Fatal(noOrders, err)
		}
		cnt := xdb.Scalar(xdb.Select[int64](nil, xdb.Count()).From(O).Where(O.CustomerID.EqCol(U.ID)))
		top, err := xdb.Select[CustomerStat](db, U.Name, cnt.As("cnt")).From(U).Where(cnt.Ge(3)).One(ctx)
		if err != nil || top.Name != "alice" || top.Cnt != 3 {
			t.Fatal(top, err)
		}

		// 派生表 + Count 包装
		grouped := xdb.Select[CustomerStat](db, O.CustomerID, xdb.Count().As("cnt")).From(O).GroupBy(O.CustomerID)
		if n, err := grouped.Count(ctx); err != nil || n != 2 {
			t.Fatal("grouped count", n, err)
		}
		d := xdb.Derived("t", grouped)
		big, err := xdb.Select[CustomerStat](db, d.Star()).From(d).Where(xdb.C[int64](d, "cnt").Gt(1)).All(ctx)
		if err != nil || len(big) != 1 || big[0].CustomerID != cs[0].ID {
			t.Fatal(big, err)
		}

		// First / Exists / Offset 无 Limit
		first, err := xdb.Query[Customer](db).OrderBy(U.Age.Desc()).First(ctx)
		if err != nil || first.Name != "carol_50%" {
			t.Fatal(first, err)
		}
		if ok, err := xdb.Query[Customer](db).Where(U.Name.Eq("nobody")).Exists(ctx); err != nil || ok {
			t.Fatal(ok, err)
		}
		rest, err := xdb.Query[Customer](db).OrderBy(U.ID.Asc()).Offset(1).All(ctx)
		if err != nil || len(rest) != 2 {
			t.Fatal(rest, err)
		}
	})
}

type TreeNode struct {
	ID       int64  `xdb:"id"`
	ParentID *int64 `xdb:"parent_id"`
	Depth    int64  `xdb:"depth"`
}

func TestBuilderRecursiveCTE(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		mustExec(t, db, "INSERT INTO nodes (id, parent_id) VALUES (1, NULL), (2, 1), (3, 2), (4, 1), (5, NULL)")
		nodes, tree := xdb.T("nodes"), xdb.T("tree")
		id, parent := xdb.C[int64](nodes, "id"), xdb.C[int64](nodes, "parent_id")
		base := xdb.Select[TreeNode](nil, id, parent, xdb.SQL[int64]("0")).From(nodes).Where(id.Eq(1))
		rec := xdb.Select[TreeNode](nil, id, parent, xdb.Add[int64](xdb.C[int64](tree, "depth"), xdb.SQL[int64]("1"))).
			From(nodes).Join(tree, parent.EqCol(xdb.C[int64](tree, "id")))
		cte := xdb.CTE("tree", base.UnionAll(rec)).Columns("id", "parent_id", "depth")
		got, err := xdb.Select[TreeNode](db).WithRecursive(cte).From(cte).OrderBy(xdb.C[int64](cte, "id").Asc()).All(ctx)
		if err != nil || len(got) != 4 || got[2].Depth != 2 {
			t.Fatalf("%+v %v", got, err)
		}
	})
}

func TestBuilderUpsertUpdateDelete(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		cs := seed(t, db)

		// DoUpdate：按 name 冲突，覆盖 age
		up := Customer{Name: "alice", Age: 31, CreatedAt: t0}
		if _, err := xdb.Insert(db, &up).OnConflict(U.Name).DoUpdate(U.Age).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		// DoUpdateSet + Excluded：累加
		inc := Customer{Name: "alice", Age: 2, CreatedAt: t0}
		if _, err := xdb.Insert(db, &inc).OnConflict(U.Name).
			DoUpdateSet(U.Age.ToExpr(xdb.Add[int](U.Age, xdb.Excluded(U.Age.Col)))).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		// DoNothing
		dup := Customer{Name: "alice", Age: 99, CreatedAt: t0}
		if n, err := xdb.Insert(db, &dup).OnConflict(U.Name).DoNothing().Exec(ctx); err != nil || n != 0 {
			t.Fatal("do nothing", n, err)
		}
		a, err := xdb.Query[Customer](db).Where(U.Name.Eq("alice")).One(ctx)
		if err != nil || a.Age != 33 || a.ID != cs[0].ID {
			t.Fatalf("upsert result %+v %v", a, err)
		}
		if db.Dialect().Name() == "postgres" && up.ID != cs[0].ID {
			t.Fatalf("RETURNING must backfill existing id on DoUpdate, got %d", up.ID)
		}
		if n, _ := xdb.Query[Customer](db).Count(ctx); n != 3 {
			t.Fatal("upsert must not add rows", n)
		}

		// Update + Incr
		n, err := xdb.Update[Order](db).Set(O.Amount.Incr(1), O.State.To("done")).Where(O.State.Eq("paid")).Exec(ctx)
		if err != nil || n != 3 {
			t.Fatal(n, err)
		}
		if _, err := xdb.Update[Order](db).Set(O.State.To("x")).Exec(ctx); !errors.Is(err, xdb.ErrMissingWhere) {
			t.Fatal("missing where", err)
		}
		// UpdateModel + 乐观条件
		b := cs[1]
		b.Age = 18
		if n, err := xdb.UpdateModel(db, &b, U.Age).Where(U.Age.Eq(17)).Exec(ctx); err != nil || n != 1 {
			t.Fatal(n, err)
		}
		if n, err := xdb.UpdateModel(db, &b, U.Age).Where(U.Age.Eq(17)).Exec(ctx); err != nil || n != 0 {
			t.Fatal("optimistic update must not match twice", n, err)
		}
		// DeleteModel
		if n, err := xdb.DeleteModel(db, &b).Exec(ctx); err != nil || n != 1 {
			t.Fatal(n, err)
		}
		if n, err := xdb.Delete[Order](db).Where(O.Amount.Lt(20)).Exec(ctx); err != nil || n != 1 {
			t.Fatal(n, err)
		}
	})
}

func TestBuilderFiltersAndCast(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		seed(t, db)

		// HasSuffix / Contains：输入中的 % _ 按字面匹配。
		one, err := xdb.Query[Customer](db).Where(U.Name.HasSuffix("_50%")).One(ctx)
		if err != nil || one.Name != "carol_50%" {
			t.Fatalf("has suffix: %+v %v", one, err)
		}
		// NotBetween 是闭区间取反：3 条里只剩 age 17。
		notMid, err := xdb.Pluck(ctx, xdb.Query[Customer](db).
			Where(U.Age.NotBetween(18, 60)).OrderBy(U.ID.Asc()), U.ID)
		if err != nil || len(notMid) != 2 {
			t.Fatalf("not between: %v %v", notMid, err)
		}
		// SUM(bigint) 在 MySQL 是 DECIMAL、PG 是 NUMERIC，必须 CAST 才能扫进 int64。
		total, err := xdb.Select[CustomerStat](db,
			xdb.Cast[int64]("BIGINT", xdb.Sum(O.Amount)).As("total"),
		).From(O).One(ctx)
		if err != nil || total.Total != 460 {
			t.Fatalf("cast sum: %+v %v", total, err)
		}
		// Union 去重；Limit 作用于组合结果。
		// UNION 的全局 ORDER BY 只能引用输出列名（SQL 标准），不能引用带表限定的列。
		ids, err := xdb.Pluck(ctx, xdb.Select[int64](db, O.CustomerID).From(O).Where(O.State.Eq("paid")).
			Union(xdb.Select[int64](db, O.CustomerID).From(O).Where(O.Amount.Gt(200))).
			OrderBy(xdb.C[int64](nil, "customer_id").Asc()).Limit(2), xdb.C[int64](nil, "customer_id"))
		if err != nil || len(ids) != 2 {
			t.Fatalf("union: %v %v", ids, err)
		}

		// MySQL 的 DoNothing 曾生成 `name` = `name`，在行别名存在时是歧义列。
		del, err := xdb.Insert(db, &Customer{Name: "alice", Age: 1, CreatedAt: t0}).
			OnConflict(U.Name).DoNothing().Exec(ctx)
		if err != nil || del != 0 {
			t.Fatalf("do nothing on existing row: n=%d err=%v", del, err)
		}
		if n, _ := xdb.Query[Customer](db).Count(ctx); n != 3 {
			t.Fatalf("do nothing must not insert, count=%d", n)
		}
	})
}

func TestBuilderLocks(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		seed(t, db)
		locked := make(chan struct{})
		release := make(chan struct{})
		var wg sync.WaitGroup
		wg.Add(1)
		go func() {
			defer wg.Done()
			_ = db.Tx(ctx, func(ctx context.Context, tx *xdb.Tx) error {
				// 锁住第一条 new/paid 订单
				if _, err := xdb.Query[Order](tx).OrderBy(O.ID.Asc()).Limit(1).ForUpdate().One(ctx); err != nil {
					t.Error(err)
				}
				close(locked)
				<-release
				return nil
			})
		}()
		<-locked
		err := db.Tx(ctx, func(ctx context.Context, tx *xdb.Tx) error {
			// SKIP LOCKED：拿到下一条未被锁的订单
			next, err := xdb.Query[Order](tx).OrderBy(O.ID.Asc()).Limit(1).ForUpdate().SkipLocked().One(ctx)
			if err != nil {
				return err
			}
			if next.ID == 1 {
				t.Error("SKIP LOCKED returned a locked row")
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
		err = db.Tx(ctx, func(ctx context.Context, tx *xdb.Tx) error {
			_, err := xdb.Query[Order](tx).Where(O.ID.Eq(1)).ForUpdate().NoWait().One(ctx)
			return err
		})
		if !errors.Is(err, xdb.ErrLockTimeout) {
			t.Fatalf("NOWAIT on locked row: want ErrLockTimeout, got %v", err)
		}
		close(release)
		wg.Wait()

		if _, err := xdb.Query[Order](db).ForUpdate().All(ctx); !errors.Is(err, xdb.ErrLockOutsideTx) {
			t.Fatal(err)
		}
	})
}
