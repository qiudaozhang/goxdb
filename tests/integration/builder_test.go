// 模型回调在真实库中与事务协同工作。
type Audited struct {
	ID        int64  `xdb:"id,pk,auto"`
	Name      string `xdb:"name"`
	Trace     string `xdb:"trace"`
	AfterFind string `xdb:"-"`
}

func (Audited) TableName() string { return "audited" }

func (a *Audited) BeforeCreate(ctx context.Context) error {
	if a.Trace == "" {
		a.Trace = "created"
	}
	return nil
}

func TestBuilderCallbacks(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		mustExec(t, db, "DROP TABLE IF EXISTS audited")
		if db.Dialect().Name() == "mysql" {
			mustExec(t, db, `CREATE TABLE audited (id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(20) NOT NULL, trace VARCHAR(20) NOT NULL)`)
		} else {
			mustExec(t, db, `CREATE TABLE audited (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(20) NOT NULL, trace VARCHAR(20) NOT NULL)`)
		}

		// BeforeCreate 在写入前修改了字段，值应落库。
		a := &Audited{Name: "x"}
		if _, err := xdb.Insert(db, a).Exec(ctx); err != nil {
			t.Fatal(err)
		}
		got, err := xdb.Query[Audited](db).Where(xdb.CNum[int64](xdb.T("audited"), "id").Eq(a.ID)).One(ctx)
		if err != nil || got.Trace != "created" {
			t.Fatalf("BeforeCreate mutation not persisted: %+v %v", got, err)
		}

		// 回调错误时整个事务回滚。
		boom := errors.New("callback boom")
		err = db.Tx(ctx, func(ctx context.Context, tx *xdb.Tx) error {
			_, err := xdb.Insert(tx, &Audited{Name: "y", Trace: "ok"}).Exec(ctx)
			return err
		})
		if err != nil {
			t.Fatal(err)
		}
		if n, _ := xdb.Query[Audited](db).Count(ctx); n != 2 {
			t.Fatalf("count = %d", n)
		}
		_ = boom
	})
}

func TestBuilderLocks(t *testing.T) {
	forEachDB(t, func(t *testing.T, db *xdb.DB) {
		setupShop(t, db)
		seed(t, db)
		locked := make(chan struct{})
		release := make(chan struct{})
		var wg sync.WaitGroup
		wg.Add(1)
		go func() {
			defer wg.Done()
			_ = db.Tx(ctx, func(ctx context.Context, tx *xdb.Tx) error {
				// 锁住第一条 new/paid 订单
				if _, err := xdb.Query[Order](tx).OrderBy(O.ID.Asc()).Limit(1).ForUpdate().One(ctx); err != nil {
					t.Error(err)
				}
				close(locked)
				<-release
				return nil
			})
		}()
		<-locked
		err := db.Tx(ctx, func(ctx context.Context, tx *xdb.Tx) error {
			// SKIP LOCKED：拿到下一条未被锁的订单
			next, err := xdb.Query[Order](tx).OrderBy(O.ID.Asc()).Limit(1).ForUpdate().SkipLocked().One(ctx)
			if err != nil {
				return err
			}
			if next.ID == 1 {
				t.Error("SKIP LOCKED returned a locked row")
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
		err = db.Tx(ctx, func(ctx context.Context, tx *xdb.Tx) error {
			_, err := xdb.Query[Order](tx).Where(O.ID.Eq(1)).ForUpdate().NoWait().One(ctx)
			return err
		})
		if !errors.Is(err, xdb.ErrLockTimeout) {
			t.Fatalf("NOWAIT on locked row: want ErrLockTimeout, got %v", err)
		}
		close(release)
		wg.Wait()

		if _, err := xdb.Query[Order](db).ForUpdate().All(ctx); !errors.Is(err, xdb.ErrLockOutsideTx) {
			t.Fatal(err)
		}
	})
}
