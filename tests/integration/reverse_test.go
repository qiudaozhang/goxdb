// DB-first：从真实数据库 schema 反向生成 Go 模型，并确认关键信息正确。
func TestReverseFromRealSchema(t *testing.T) {
	for _, tg := range targets {
		t.Run(tg.dialect, func(t *testing.T) {
			var (
				in     dialect.Introspector
				driver string
			)
			if tg.dialect == "mysql" {
				in, driver = mysqld.Introspect, "mysql"
			} else {
				in, driver = pgd.Introspect, "pgx"
			}

			db, err := sql.Open(driver, tg.dsn)
			if err != nil {
				t.Fatal(err)
			}
			defer db.Close()

			ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
			defer cancel()
			if err := db.PingContext(ctx); err != nil {
				t.Skipf("database not reachable (%v); run docker compose up -d --wait", err)
			}

			mustExecRaw(t, ctx, db, "DROP TABLE IF EXISTS reverse_demo")
			switch tg.dialect {
			case "mysql":
				mustExecRaw(t, ctx, db, `CREATE TABLE reverse_demo (
					id BIGINT AUTO_INCREMENT PRIMARY KEY,
					name VARCHAR(50) NOT NULL,
					note VARCHAR(100) NULL,
					amount DECIMAL(10,2) NOT NULL,
					created_at DATETIME(6) NOT NULL)`)
			default:
				mustExecRaw(t, ctx, db, `CREATE TABLE reverse_demo (
					id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
					name VARCHAR(50) NOT NULL,
					note VARCHAR(100) NULL,
					amount NUMERIC(10,2) NOT NULL,
					created_at TIMESTAMPTZ NOT NULL)`)
			}

			src, err := reverse.Generate(ctx, db, in, reverse.Config{
				Tables: []string{"reverse_demo"},
				Pkg:    "model",
			})
			if err != nil {
				t.Fatal(err)
			}
			out := string(src)
			for _, want := range []string{
				"type ReverseDemo struct {",
				`xdb:"id,pk,auto"`,
				`xdb:"name"`,
				`xdb:"note"`,
				"Note *string", // 可空列 → 指针
				`xdb:"created_at,autoCreateTime"`,
				`return "reverse_demo"`,
			} {
				if !strings.Contains(out, want) {
					t.Errorf("missing %q in:\n%s", want, out)
				}
			}

			// 指定不存在的表必须报错，而不是静默生成空文件
			if _, err := reverse.Generate(ctx, db, in, reverse.Config{
				Tables: []string{"no_such_table"},
				Pkg:    "model",
			}); err == nil {
				t.Fatal("missing table must be reported")
			}
		})
	}
}

func mustExecRaw(t *testing.T, ctx context.Context, db *sql.DB, q string, args ...any) {
	t.Helper()
	if _, err := db.ExecContext(ctx, q, args...); err != nil {
		t.Fatalf("%s: %v", q, err)
	}
}
