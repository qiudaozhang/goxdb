// impl 是每个框架需要实现的基准操作集合。所有操作作用于同一组表与同一个连接池，
// 因此测出的是「框架开销 + 驱动 + 服务端」的端到端成本。
//
// 除直接返回 error 的操作外，带校验的操作会在结果不符合预期时返回错误，
// 避免某个框架「用更少的活儿换来更快的数字」。
type impl struct {
	// SelectOne 按主键取一行并扫描到结构体。
	SelectOne func(ctx context.Context, id int64) error
	// SelectMany 按条件取 100 行并扫描。
	SelectMany func(ctx context.Context) error
	// SelectPage 分页：第 2 页，每页 20 行。检验 LIMIT/OFFSET 生成。
	SelectPage func(ctx context.Context, page, size int64) error
	// Count 带条件计数。
	Count func(ctx context.Context) error
	// InsertOne 插入一行（框架负责自增主键回填）。
	InsertOne func(ctx context.Context, u *BenchUser) error
	// InsertBatch 批量插入 100 行（单条多值 INSERT）。
	InsertBatch func(ctx context.Context, rows []BenchUser) error
	// UpdateOne 按主键更新一行的 name。
	UpdateOne func(ctx context.Context, id int64, name string) error
	// Upsert 冲突时更新：name 上有唯一索引。
	Upsert func(ctx context.Context, u *BenchUser) error
	// Preload 加载 50 个用户及其订单（两次查询，不做 N+1）。
	Preload func(ctx context.Context) error
	// JoinAggregate 用 JOIN + GROUP BY 统计每个用户的订单总额。
	JoinAggregate func(ctx context.Context) error
	// Tx 执行一个事务：读一行 + 更新一行 + 提交。
	Tx func(ctx context.Context, id int64, name string) error
}

type backend struct {
	name        string
	env         string
	defaultDSN  string
	driver      string
	placeholder func(n int) string
}

