func (b backend) dsn() string {
	if v := os.Getenv(b.env); v != "" {
		return v
	}
	return b.defaultDSN
}

const (
	seedUsers  = 1000
	seedOrders = 5000 // 每个用户 5 单
	preloadN   = 50
	pageSize   = 20
)

var seedTime = time.Unix(0, 0).UTC()

// createTable 建表并灌入种子数据。订单表对 users 有外键，删除顺序相反。
func createTable(ctx context.Context, db *sql.DB, b backend) error {
	for _, q := range []string{
		"DROP TABLE IF EXISTS " + orderTable,
		"DROP TABLE IF EXISTS " + tableName,
	} {
		if _, err := db.ExecContext(ctx, q); err != nil {
			return err
		}
	}

	var usersDDL, ordersDDL string
	if b.name == "mysql" {
		usersDDL = `CREATE TABLE ` + tableName + ` (
			id BIGINT AUTO_INCREMENT PRIMARY KEY,
			name VARCHAR(50) NOT NULL,
			email VARCHAR(100) NULL,
			age INT NOT NULL,
			created_at DATETIME(6) NOT NULL,
			UNIQUE KEY uk_bench_name (name)
		)`
		ordersDDL = `CREATE TABLE ` + orderTable + ` (
			id BIGINT AUTO_INCREMENT PRIMARY KEY,
			user_id BIGINT NOT NULL,
			amount BIGINT NOT NULL,
			state VARCHAR(20) NOT NULL,
			created_at DATETIME(6) NOT NULL,
			KEY idx_bench_user (user_id)
		)`
	} else {
		usersDDL = `CREATE TABLE ` + tableName + ` (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			name VARCHAR(50) NOT NULL UNIQUE,
			email VARCHAR(100),
			age INT NOT NULL,
			created_at TIMESTAMPTZ NOT NULL
		)`
		ordersDDL = `CREATE TABLE ` + orderTable + ` (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			user_id BIGINT NOT NULL REFERENCES ` + tableName + `(id),
			amount BIGINT NOT NULL,
			state VARCHAR(20) NOT NULL,
			created_at TIMESTAMPTZ NOT NULL
		)`
	}
	for _, q := range []string{usersDDL, ordersDDL} {
		if _, err := db.ExecContext(ctx, q); err != nil {
			return err
		}
	}
	if b.name == "postgres" {
		q := `CREATE INDEX idx_bench_user ON ` + orderTable + ` (user_id)`
		if _, err := db.ExecContext(ctx, q); err != nil {
			return err
		}
	}

	if err := seedUsersData(ctx, db, b); err != nil {
		return err
	}
	if err := seedOrdersData(ctx, db, b); err != nil {
		return err
	}
	if err := resetIdentity(ctx, db, b); err != nil {
		return err
	}
	return analyzeTables(ctx, db, b)
}

// analyzeTables 刷新优化器统计信息。
//
// 灌数与每个场景后的清理都会让统计信息过期。MySQL 曾因此把 JOIN 聚合估成
// 「30 个用户、1 个订单」，选出慢 3 倍的计划；统计何时被后台自动刷新
// 是随机的，于是谁恰好跑在刷新之后谁就快（bun 0.45ms vs 其余 1.4ms，
// GORM 三次里有一次 0.6ms）。显式 ANALYZE 让每个框架面对同一个计划。
func analyzeTables(ctx context.Context, db *sql.DB, b backend) error {
	q := "ANALYZE " + tableName + ", " + orderTable
	if b.name == "mysql" {
		q = "ANALYZE TABLE " + tableName + ", " + orderTable
	}
	rows, err := db.QueryContext(ctx, q) // MySQL 的 ANALYZE TABLE 返回结果集
	if err != nil {
		return err
	}
	return rows.Close()
}

// seedUsersData 一次多值 INSERT 灌入 users，避免逐行往返拖慢启动。
func seedUsersData(ctx context.Context, db *sql.DB, b backend) error {
	ph := b.placeholder
	const chunk = 100
	for start := 1; start <= seedUsers; start += chunk {
		end := min(start+chunk-1, seedUsers)
		q := "INSERT INTO " + tableName + " (id, name, email, age, created_at) VALUES "
		args := make([]any, 0, (end-start+1)*4)
		for i := start; i <= end; i++ {
			if i > start {
				q += ", "
			}
			n := len(args)
			q += fmt.Sprintf("(%s, %s, NULL, %s, %s)", ph(n+1), ph(n+2), ph(n+3), ph(n+4))
			args = append(args, i, fmt.Sprintf("user-%d", i), 18+i%50, seedTime)
		}
		if _, err := db.ExecContext(ctx, q, args...); err != nil {
			return err
		}
	}
	return nil
}

func seedOrdersData(ctx context.Context, db *sql.DB, b backend) error {
	ph := b.placeholder
	const chunk = 100
	states := []string{"paid", "new", "paid", "paid", "cancelled"}
	for start := 1; start <= seedOrders; start += chunk {
		end := min(start+chunk-1, seedOrders)
		q := "INSERT INTO " + orderTable + " (id, user_id, amount, state, created_at) VALUES "
		args := make([]any, 0, (end-start+1)*4)
		for i := start; i <= end; i++ {
			if i > start {
				q += ", "
			}
			n := len(args)
			q += fmt.Sprintf("(%s, %s, %s, %s, %s)", ph(n+1), ph(n+2), ph(n+3), ph(n+4), ph(n+5))
			user := (i-1)/5 + 1
			args = append(args, i, user, int64(10*(i%97+1)), states[i%len(states)], seedTime)
		}
		if _, err := db.ExecContext(ctx, q, args...); err != nil {
			return err
		}
	}
	return nil
}

// resetIdentity 把自增序列推进到种子之后：显式插入过 id，序列不会自动前进。
func resetIdentity(ctx context.Context, db *sql.DB, b backend) error {
	if b.name == "mysql" {
		q := fmt.Sprintf("ALTER TABLE %s AUTO_INCREMENT = %d", tableName, seedUsers+1)
		if _, err := db.ExecContext(ctx, q); err != nil {
			return err
		}
		q = fmt.Sprintf("ALTER TABLE %s AUTO_INCREMENT = %d", orderTable, seedOrders+1)
		_, err := db.ExecContext(ctx, q)
		return err
	}
	for _, t := range []struct {
		name string
		next int
	}{{tableName, seedUsers + 1}, {orderTable, seedOrders + 1}} {
		q := fmt.Sprintf("ALTER TABLE %s ALTER COLUMN id RESTART WITH %d", t.name, t.next)
		if _, err := db.ExecContext(ctx, q); err != nil {
			return err
		}
	}
	return nil
}

// dropTables 清理基准产生的数据。
func dropTables(ctx context.Context, db *sql.DB) {
	_, _ = db.ExecContext(ctx, "DROP TABLE IF EXISTS "+orderTable)
	_, _ = db.ExecContext(ctx, "DROP TABLE IF EXISTS "+tableName)
}
