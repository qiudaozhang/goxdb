package codegen

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeModel(t *testing.T, dir, src string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, "model.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
}

const sampleModel = `package model

import "time"

type User struct {
	ID        int64     ` + "`xdb:\"id,pk,auto\"`" + `
	Name      string    ` + "`xdb:\"name\"`" + `
	Email     *string   ` + "`xdb:\"email\"`" + `
	Age       int       ` + "`xdb:\"age\"`" + `
	CreatedAt time.Time ` + "`xdb:\"created_at\"`" + `
	Ignored   string
	Orders    []Order ` + "`xdb:\"rel:has_many,fk:user_id\"`" + `
}

func (User) TableName() string { return "members" }

type Order struct {
	ID     int64  ` + "`xdb:\"id,pk,auto\"`" + `
	UserID int64  ` + "`xdb:\"user_id\"`" + `
	State  string ` + "`xdb:\"state\"`" + `
}

// DTO 没有 xdb 标签，不应生成描述符。
type DTO struct {
	Foo string
}
`

func TestParseDir(t *testing.T) {
	dir := t.TempDir()
	writeModel(t, dir, sampleModel)

	models, pkg, err := ParseDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if pkg != "model" {
		t.Fatalf("pkg = %q", pkg)
	}
	if len(models) != 2 {
		t.Fatalf("want 2 models, got %d: %+v", len(models), models)
	}
	// 按类型名排序
	if models[0].Name != "Order" || models[1].Name != "User" {
		t.Fatalf("order: %s %s", models[0].Name, models[1].Name)
	}
	u := models[1]
	if u.Table != "members" {
		t.Fatalf("TableName() must win, got %q", u.Table)
	}
	if !u.HasPK {
		t.Fatal("pk not detected")
	}
	var cols []string
	for _, c := range u.Columns {
		cols = append(cols, c.Column)
	}
	if got, want := strings.Join(cols, ","), "id,name,email,age,created_at"; got != want {
		t.Fatalf("columns = %s, want %s", got, want)
	}
	if len(u.Rels) != 1 || u.Rels[0].Kind != "has_many" || u.Rels[0].FK != "user_id" {
		t.Fatalf("relations: %+v", u.Rels)
	}
	// Order 没有 TableName()，走 snake_case 复数
	if models[0].Table != "orders" {
		t.Fatalf("derived table = %q", models[0].Table)
	}
}

func TestColumnKinds(t *testing.T) {
	dir := t.TempDir()
	writeModel(t, dir, sampleModel)
	models, _, err := ParseDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	u := models[1]
	want := map[string]string{
		"id":         "xdb.NumberCol[int64]",
		"name":       "xdb.StringCol",
		"email":      "xdb.StringCol", // *string 按值类型归类
		"age":        "xdb.NumberCol[int]",
		"created_at": "xdb.TimeCol",
	}
	for _, c := range u.Columns {
		if got := colType(c); got != want[c.Column] {
			t.Errorf("%s: %s, want %s", c.Column, got, want[c.Column])
		}
	}
}

func TestRender(t *testing.T) {
	dir := t.TempDir()
	writeModel(t, dir, sampleModel)
	models, pkg, err := ParseDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	src, err := Render(pkg, models)
	if err != nil {
		t.Fatal(err)
	}
	out := string(src)
	for _, want := range []string{
		"// Code generated by goxdb. DO NOT EDIT.",
		"var O = struct {",
		"var U = struct {",
		"xdb.CNum[int64](U.Table, \"id\")",
		"xdb.CStr(U.Table, \"name\")",
		"xdb.CTime(U.Table, \"created_at\")",
		"U.Table = xdb.TableOf[User]()",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("generated source missing %q\n%s", want, out)
		}
	}
	// 描述符变量不能与类型名相同，否则无法编译
	if strings.Contains(out, "var User = struct") {
		t.Error("descriptor variable must not shadow the type name")
	}
	// DTO 没有标签，不应出现
	if strings.Contains(out, "DTO") {
		t.Error("untagged struct must not be generated")
	}
}

func TestVarName(t *testing.T) {
	for _, c := range []struct{ in, want string }{
		{"User", "U"},
		{"Order", "O"},
		{"UserProfile", "UP"},
		{"U", "UTable"}, // 与类型名相同，必须回退
	} {
		if got := varName(c.in); got != c.want {
			t.Errorf("varName(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

// 生成文件必须能被 gofmt 解析（Render 内部已格式化，这里再校验一次解析不报错）。
func TestRenderIsValidGo(t *testing.T) {
	dir := t.TempDir()
	writeModel(t, dir, sampleModel)
	models, pkg, err := ParseDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	src, err := Render(pkg, models)
	if err != nil {
		t.Fatal(err)
	}
	// 二次解析：Render 已调用 format.Source，此处确认幂等
	src2, err := Render(pkg, models)
	if err != nil {
		t.Fatal(err)
	}
	if string(src) != string(src2) {
		t.Fatal("Render must be deterministic")
	}
}
