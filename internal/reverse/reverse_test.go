func TestRender(t *testing.T) {
	tables := []dialect.Table{
		{
			Name: "user_profiles",
			Columns: []dialect.Column{
				{Name: "id", DataType: "bigint", IsPK: true, AutoInc: true, Type: reflect.TypeFor[int64]()},
				{Name: "user_id", DataType: "bigint", Type: reflect.TypeFor[int64]()},
				{Name: "display_name", DataType: "varchar(50)", Nullable: true, Type: reflect.TypeFor[*string]()},
				{Name: "score", DataType: "numeric(10,2)", Type: reflect.TypeFor[float64]()},
				{Name: "created_at", DataType: "timestamptz", Type: reflect.TypeFor[time.Time]()},
			},
			PK: []string{"id"},
		},
	}
	src, err := Render(Config{Pkg: "model"}, tables)
	if err != nil {
		t.Fatal(err)
	}
	out := string(src)
	for _, want := range []string{
		"// Code generated by goxdb reverse. DO NOT EDIT.",
		"package model",
		"import \"time\"",
		"type UserProfile struct {",
		`ID int64 ` + "`" + `xdb:"id,pk,auto"` + "`",
		`UserID int64 ` + "`" + `xdb:"user_id"` + "`",
		`DisplayName *string ` + "`" + `xdb:"display_name"` + "`",
		`Score float64 ` + "`" + `xdb:"score"` + "`",
		`CreatedAt time.Time ` + "`" + `xdb:"created_at,autoCreateTime"` + "`",
		`func (UserProfile) TableName() string { return "user_profiles" }`,
		"// varchar(50), nullable",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in:\n%s", want, out)
		}
	}
}

func TestPrefixSuffix(t *testing.T) {
	tables := []dialect.Table{{
		Name:    "t_orders_v2",
		Columns: []dialect.Column{{Name: "id", Type: reflect.TypeFor[int64](), IsPK: true}},
	}}
	src, err := Render(Config{Pkg: "model", Prefix: "t_", Suffix: "_v2"}, tables)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(src), "type Order struct") {
		t.Fatalf("prefix/suffix not stripped:\n%s", src)
	}
}

// 结构体名冲突时必须自动去重，否则生成的文件无法编译。
func TestNameCollision(t *testing.T) {
	tables := []dialect.Table{
		{Name: "user", Columns: []dialect.Column{{Name: "id", Type: reflect.TypeFor[int64]()}}},
		{Name: "users", Columns: []dialect.Column{{Name: "id", Type: reflect.TypeFor[int64]()}}},
	}
	src, err := Render(Config{Pkg: "model"}, tables)
	if err != nil {
		t.Fatal(err)
	}
	out := string(src)
	// user 与 users 都会推导为 User，第二个必须自动加序号，否则无法编译。
	if !strings.Contains(out, "type User struct") || !strings.Contains(out, "type User2 struct") {
		t.Fatalf("collision must be deduplicated:\n%s", out)
	}
}

// 没有时间列时不应导入 time（否则 unused import 导致编译失败）。
func TestNoTimeImport(t *testing.T) {
	tables := []dialect.Table{{
		Name:    "tags",
		Columns: []dialect.Column{{Name: "id", Type: reflect.TypeFor[int64]()}},
	}}
	src, err := Render(Config{Pkg: "model"}, tables)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(src), `import "time"`) {
		t.Fatalf("must not import time:\n%s", src)
	}
}

func TestFieldName(t *testing.T) {
	for _, c := range []struct{ in, want string }{
		{"id", "ID"},
		{"user_id", "UserID"},
		{"created_at", "CreatedAt"},
		{"a_b_c", "ABC"},
	} {
		if got := fieldName(c.in); got != c.want {
			t.Errorf("fieldName(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

func TestStructName(t *testing.T) {
	// structName 只做命名风格转换，单数化由 singular 负责（见 buildModel）。
	for _, c := range []struct{ in, want string }{
		{"user_profiles", "UserProfiles"},
		{"user", "User"},
		{"order_items", "OrderItems"},
	} {
		if got := structName(c.in); got != c.want {
			t.Errorf("structName(%q) = %q, want %q", c.in, got, c.want)
		}
	}
	for _, c := range []struct{ in, want string }{
		{"users", "user"},
		{"user_profiles", "user_profile"},
		{"boxes", "box"},
		{"categories", "category"},
		{"status", "status"}, // 以 ss 结尾不剥
	} {
		if got := singular(c.in); got != c.want {
			t.Errorf("singular(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

func TestAutoTimeOnlyForTimeColumns(t *testing.T) {
	// created_at 是字符串列时不应自动打时间戳标签
	tables := []dialect.Table{{
		Name: "weird",
		Columns: []dialect.Column{
			{Name: "created_at", DataType: "varchar(20)", Type: reflect.TypeFor[string]()},
		},
	}}
	src, err := Render(Config{Pkg: "model"}, tables)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(src), "autoCreateTime") {
		t.Fatalf("must not tag non-time column:\n%s", src)
	}
}
