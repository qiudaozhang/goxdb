// Package reverse 从已有数据库 schema 反向生成 goxdb 模型结构体（DB-first）。
//
// 与 codegen（model-first）互补：codegen 读 Go 源码生成描述符，
// reverse 读数据库生成 Go 源码。
package reverse

import (
	"bytes"
	"context"
	"database/sql"
	"fmt"
	"go/format"
	"reflect"
	"sort"
	"strings"
	"time"
	"unicode"

	"github.com/qiudaozhang/goxdb/dialect"
)

// Config 控制生成行为。
type Config struct {
	// Tables 指定要生成的表；为空时生成全部表。
	Tables []string
	// Pkg 是生成文件的包名。
	Pkg string
	// Prefix / Suffix 会从表名中去掉后用于推导结构体名，
	// 例如 Prefix 为 "t_" 时 t_user 生成 User。
	Prefix string
	Suffix string
}

// Generate 读取数据库 schema 并返回格式化的 Go 源码。
// 生成的模型包含 xdb 标签（列名、pk、auto）以及注释中的原始数据库类型。
func Generate(ctx context.Context, db *sql.DB, in dialect.Introspector, cfg Config) ([]byte, error) {
	if cfg.Pkg == "" {
		cfg.Pkg = "model"
	}
	tables, err := in.ListTables(ctx, db)
	if err != nil {
		return nil, err
	}
	if len(cfg.Tables) > 0 {
		want := map[string]bool{}
		for _, t := range cfg.Tables {
			want[t] = true
		}
		var kept []string
		for _, t := range tables {
			if want[t] {
				kept = append(kept, t)
				delete(want, t)
			}
		}
		if len(want) > 0 {
			missing := make([]string, 0, len(want))
			for t := range want {
				missing = append(missing, t)
			}
			sort.Strings(missing)
			return nil, fmt.Errorf("reverse: table(s) not found: %v", missing)
		}
		tables = kept
	}

	infos := make([]dialect.Table, 0, len(tables))
	for _, name := range tables {
		t, err := in.DescribeTable(ctx, db, name)
		if err != nil {
			return nil, fmt.Errorf("reverse: describe %s: %w", name, err)
		}
		infos = append(infos, *t)
	}
	return Render(cfg, infos)
}

// Render 由已读取的表信息生成源码。
func Render(cfg Config, tables []dialect.Table) ([]byte, error) {
	models := make([]model, 0, len(tables))
	used := map[string]int{}
	for _, t := range tables {
		m := buildModel(cfg, t)
		// 结构体名冲突时追加序号，避免生成无法编译的代码。
		if n := used[m.Name]; n > 0 {
			m.Name = fmt.Sprintf("%s%d", m.Name, n+1)
		}
		used[m.Name]++
		models = append(models, m)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by goxdb reverse. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", cfg.Pkg)
	if importsTime(models) {
		fmt.Fprintf(&b, "import \"time\"\n\n")
	}
	for _, m := range models {
		fmt.Fprintf(&b, "// %s 对应表 %s。\n", m.Name, m.Table)
		fmt.Fprintf(&b, "type %s struct {\n", m.Name)
		for _, f := range m.Fields {
			if f.Comment != "" {
				fmt.Fprintf(&b, "\t// %s\n", f.Comment)
			}
			fmt.Fprintf(&b, "\t%s %s `%s`\n", f.GoName, f.GoType, f.Tag)
		}
		fmt.Fprintf(&b, "}\n\n")
		fmt.Fprintf(&b, "func (%s) TableName() string { return %q }\n\n", m.Name, m.Table)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("reverse: format: %w\n%s", err, b.String())
	}
	return src, nil
}

type model struct {
	Name   string
	Table  string
	Fields []field
}

type field struct {
	GoName  string
	GoType  string
	Tag     string
	Comment string
}

func buildModel(cfg Config, t dialect.Table) model {
	name := t.Name
	if cfg.Prefix != "" {
		name = strings.TrimPrefix(name, cfg.Prefix)
	}
	if cfg.Suffix != "" {
		name = strings.TrimSuffix(name, cfg.Suffix)
	}
	m := model{Name: structName(singular(name)), Table: t.Name}

	seen := map[string]int{}
	for _, c := range t.Columns {
		goName := fieldName(c.Name)
		if goName == "TableName" {
			// 与生成的 TableName() 方法同名会编译失败；标签里仍是原列名。
			goName = "TableNameCol"
		}
		if n := seen[goName]; n > 0 {
			goName = fmt.Sprintf("%s%d", goName, n+1)
		}
		seen[goName]++

		opts := []string{c.Name}
		if c.IsPK {
			opts = append(opts, "pk")
		}
		if c.AutoInc {
			opts = append(opts, "auto")
		}
		if key := columnKey(c); key != "" && isTimeType(c.Type) {
			opts = append(opts, key)
		}
		tag := "xdb:\"" + strings.Join(opts, ",") + "\""

		comment := c.DataType
		if c.Nullable {
			comment += ", nullable"
		}
		if c.Default != "" {
			comment += ", default=" + c.Default
		}
		m.Fields = append(m.Fields, field{
			GoName:  goName,
			GoType:  goTypeName(c.Type),
			Tag:     tag,
			Comment: comment,
		})
	}
	return m
}

// isTimeType 判断列类型是否为 time.Time 或 *time.Time：只有真正的时间列才补
// autoCreateTime / autoUpdateTime 标签，避免误标（例如 created_at 存的是 Unix 秒）。
func isTimeType(t reflect.Type) bool {
	if t != nil && t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	return t == reflect.TypeFor[time.Time]()
}

// columnKey 按常见的创建/更新时间列名返回对应的时间戳标签选项。
func columnKey(c dialect.Column) string {
	switch strings.ToLower(c.Name) {
	case "created_at", "create_time", "created_time", "created":
		return "autoCreateTime"
	case "updated_at", "update_time", "updated_time", "modified_at":
		return "autoUpdateTime"
	}
	return ""
}

// structName 把表名转换为导出的 Go 类型名：user_profiles -> UserProfile。
func structName(s string) string {
	parts := splitIdent(s)
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		r := []rune(p)
		b.WriteRune(unicode.ToUpper(r[0]))
		b.WriteString(string(r[1:]))
	}
	name := b.String()
	if name == "" {
		name = "Table"
	}
	// 避免与常见类型冲突
	if !unicode.IsUpper([]rune(name)[0]) {
		name = "T" + name
	}
	return name
}

// fieldName 把列名转换为导出的 Go 字段名：user_id -> UserID。
func fieldName(s string) string {
	parts := splitIdent(s)
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		if p == "id" {
			b.WriteString("ID")
			continue
		}
		r := []rune(p)
		b.WriteRune(unicode.ToUpper(r[0]))
		b.WriteString(string(r[1:]))
	}
	out := b.String()
	// 首字符必须是大写字母，字段才是合法且导出的标识符（运行时只映射导出字段）：
	// 数字开头（2fa）或无大小写的文字（中文列名）都加前缀。
	if r := []rune(out); len(r) == 0 || !unicode.IsUpper(r[0]) {
		out = "Col" + out
	}
	return out
}

// singular 把常见的复数表名转回单数，使生成的结构体名符合 Go 习惯
// （表 users -> 类型 User）。只处理规则复数，不追求全量英语词形还原。
func singular(s string) string {
	switch {
	case strings.HasSuffix(s, "ies") && len(s) > 3:
		return s[:len(s)-3] + "y"
	case strings.HasSuffix(s, "ses"), strings.HasSuffix(s, "xes"), strings.HasSuffix(s, "zes"),
		strings.HasSuffix(s, "ches"), strings.HasSuffix(s, "shes"):
		return s[:len(s)-2]
	case strings.HasSuffix(s, "s") && !strings.HasSuffix(s, "ss") &&
		!strings.HasSuffix(s, "us") && !strings.HasSuffix(s, "is") && len(s) > 1:
		// status / analysis 这类词不是复数，保持原样。
		return s[:len(s)-1]
	}
	return s
}

// splitIdent 按非字母数字字符切分标识符；分隔符与 Go 标识符里不合法的字符（#、$ 等）一并丢弃。
func splitIdent(s string) []string {
	return strings.FieldsFunc(s, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
}

func goTypeName(t reflect.Type) string {
	if t == nil {
		return "any"
	}
	switch t.Kind() {
	case reflect.Pointer:
		return "*" + goTypeName(t.Elem())
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return "[]byte"
		}
		return "[]" + goTypeName(t.Elem())
	}
	if t == reflect.TypeFor[time.Time]() {
		return "time.Time"
	}
	return t.String()
}

func importsTime(models []model) bool {
	for _, m := range models {
		for _, f := range m.Fields {
			if strings.Contains(f.GoType, "time.Time") {
				return true
			}
		}
	}
	return false
}
